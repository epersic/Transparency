"""CLI: the DLL proxy generator. For a DLL the target loads, produce a build
folder — without touching the application's own files — that contains a
proxy.c (DllMain with a marked payload slot), a .def file, a Makefile, and a
renamed copy of the legitimate DLL. Compile the proxy, name it like the
original, place it where the application loads it from, and keep the renamed
original next to it.

Two export styles:
  forward — .def forwarders ("Name=orig.Name"): the loader binds imports
      straight into the original. Simplest, MSVC-compatible, but the export
      table openly announces the forwarding.
  call — real wrapper functions: the export table points at genuine code in
      .text that loads the original once and calls through a resolved
      pointer. Nothing in the exports says "proxy".

Both styles can carry benign decoy code (junk): an idiomatic utility library,
string tables and DllMain init work, plus ABI-safe filler inside wrappers, so
the DLL's static profile looks like an ordinary support library rather than a
thin trampoline."""

