# ABI-safe filler sequences injected into wrappers (junk mode): MSVC-style
# multi-byte NOPs and arithmetic on saved non-volatile registers only.

def _x64_filler(rng: random.Random) -> list[str]:
    out = []
    for _ in range(rng.randint(0, 3)):
        kind = rng.randrange(4)
        if kind == 0:
            out += ["    xchg %ax, %ax", "    nopw %cs:0x0(%rax,%rax,1)"]
        elif kind == 1:
            out += ["    push %rbx",
                    f"    mov ${hex(rng.randrange(1 << 31))}, %ebx",
                    f"    add ${hex(rng.randrange(1 << 16))}, %ebx",
                    f"    imul ${hex(rng.randrange(2, 4096))}, %ebx, %ebx",
                    "    pop %rbx"]
        elif kind == 2:
            out += ["    push %r12", "    push %r13",
                    f"    mov ${hex(rng.randrange(1 << 31))}, %r12d",
                    f"    xor ${hex(rng.randrange(1 << 16))}, %r12d",
                    f"    mov %r12d, %r13d",
                    f"    add ${hex(rng.randrange(1 << 16))}, %r13d",
                    "    pop %r13", "    pop %r12"]
        else:
            out += ["    nopl (%rax)", "    xchg %ax, %ax"]
    return out


def _x86_filler(rng: random.Random) -> list[str]:
    out = []
    for _ in range(rng.randint(0, 3)):
        kind = rng.randrange(3)
        if kind == 0:
            out += ["    xchg %ax, %ax", "    nop"]
        elif kind == 1:
            out += ["    push %ebx",
                    f"    mov ${hex(rng.randrange(1 << 31))}, %ebx",
                    f"    add ${hex(rng.randrange(1 << 16))}, %ebx",
                    f"    imul ${hex(rng.randrange(2, 4096))}, %ebx, %ebx",
                    "    pop %ebx"]
        else:
            out += ["    push %esi",
                    f"    mov ${hex(rng.randrange(1 << 31))}, %esi",
                    f"    xor ${hex(rng.randrange(1 << 16))}, %esi",
                    "    pop %esi"]
    return out


# ---------------------------------------------------------------------------
# Bulk decoy synthesis: enough ordinary-looking code that the compiled proxy
# matches the ORIGINAL DLL's file size, hiding the loader among a comparable
# mass of real code. Functions are assembled from composable statement
# templates with randomized constants, names and cross-calls, grouped into
# modules with their own data tables and dispatchers so the call graph is
# dense and organic.

_JPFX = ("parse_", "calc_", "enc_", "mix_", "scan_", "fold_", "norm_",
         "eval_", "conv_", "pack_", "walk_", "apply_", "decode_", "refine_",
         "digest_", "update_", "measure_", "smooth_", "quant_", "expand_")
_JNOUN = ("token", "buffer", "glyph", "rune", "scalar", "cursor", "marker",
          "header", "slot", "entry", "field", "record", "chunk", "plane",
          "tile", "node", "latch", "phase", "stage", "wave", "digit",
          "delta", "mask", "cell", "bank", "line", "pitch", "rung")
_JSIGS = (
    ("static unsigned {name}(unsigned x)", ["x"]),
    ("static unsigned {name}(const unsigned char *p, size_t n)", ["p", "n"]),
    ("static int {name}(int a, int b)", ["a", "b"]),
)


def _junk_body(rng: random.Random, sig_idx: int, name: str,
               sibs: list[tuple[str, int]]) -> list[str]:
    """One function body assembled from randomized statement blocks."""
    c = lambda: rng.randrange(2, 0xFFFFFF)          # an unsigned-ish constant
    s = lambda: rng.choice(_DECOY_STRINGS)          # a benign string
    lines = ["    unsigned acc = 0x{:x}u;".format(rng.randrange(1, 1 << 32)),
             "    size_t i = (size_t)(acc & 0xff);",
             "    unsigned char local[32];",
             "    (void)local; (void)i;"]

    for _ in range(rng.randint(2, 4)):
        block = rng.randrange(7)
        if block == 0:  # byte-class scan
            lines += ["    for (i = 0; i < 32; i++) {",
                      "        acc = (acc << 3) | (acc >> 29);",
                      f"        acc ^= local[i] + {c()};",
                      "        if ((local[i] & 0xC0) == 0x80)",
                      f"            acc += {c()};",
                      "        else if (local[i] < 0x20)",
                      f"            acc -= {c()};",
                      "    }"]
        elif block == 1:  # switch buckets
            lines += ["    switch (acc & 3) {",
                      f"    case 0: acc += {c()}; break;",
                      f"    case 1: acc ^= {c()}; break;",
                      f"    case 2: acc = acc * {c()} + (unsigned)i; break;",
                      "    default: acc >>= 1; break;",
                      "    }"]
        elif block == 2:  # state walk
            lines += ["    {",
                      "        unsigned st = acc & 7;",
                      "        while (st != 5 && i < 32) {",
                      f"            st = (st * {rng.randrange(3, 251)} + local[i]) & 7;",
                      "            i++;",
                      "        }",
                      "        acc ^= st;",
                      "    }"]
        elif block == 3:  # cross-call into a sibling
            if sibs:
                sib, sidx = rng.choice(sibs)
                if sidx == 0:
                    lines += [f"    acc ^= {sib}(acc ^ {c()});"]
                elif sidx == 1:
                    lines += ["    {",
                              "        const char *ts = \"%s\";" % s(),
                              f"        acc ^= {sib}((const unsigned char *)ts, sizeof ts);".replace("sizeof ts", "sizeof(\"%s\") - 1" % s()),
                              "    }"]
                else:
                    lines += [f"    acc ^= (unsigned){sib}((int)(acc & 0xffff), {rng.randrange(1, 9999)});"]
            else:
                lines += [f"    acc ^= aux_hash_string(\"{s()}\", {c()});"]
        elif block == 4:  # memory helpers
            lines += ["    if (i > 4) {",
                      "        memcpy(local, \"0123456789abcdef0123456789abcdef\", 32);",
                      "        acc ^= (unsigned)local[i % 32];",
                      "    } else {",
                      "        acc ^= (unsigned)strlen(\"%s\");" % s(),
                      "    }"]
        elif block == 5:  # matrix walk
            lines += ["    for (size_t r = 0; r < 4; r++)",
              "        for (size_t q = 0; q < 4; q++)",
              f"            acc += (unsigned)local[(r * 4 + q) % 32] * (unsigned)(r + q + {rng.randrange(2, 97)});"]
        else:  # conditional ladder
            lines += ["    if (acc & 1)",
                      f"        acc = acc * 3 + {c()};",
                      "    else if (acc & 2)",
                      f"        acc = acc * 5 ^ {c()};",
                      "    else",
                      f"        acc += (unsigned)(i << {rng.randrange(1, 12)});",
                      f"    if (acc > {c() << 4})",
                      "        acc >>= 2;"]

    # merge the signature's parameters into the accumulator
    if sig_idx == 0:
        lines.append("    acc ^= x;")
        lines.append("    return acc;")
    elif sig_idx == 1:
        lines.append("    if (p && n)")
        lines.append("        acc ^= (unsigned)p[0] + (unsigned)n;")
        lines.append("    return acc;")
    else:
        lines.append("    acc ^= (unsigned)(a + b);")
        lines.append("    return (int)acc;")
    return lines


def _emit_bulk(rng: random.Random, target_bytes: int, reserve_bytes: int):
    """(code, init_call, n_functions) — enough decoy functions to grow the
    compiled proxy to roughly target_bytes."""
    budget = max(0, target_bytes - reserve_bytes)
    n = budget // BYTES_PER_FUNCTION
    if n < 24:
        return "", "", 0  # tiny originals: the small decoy library is enough
    n = min(n, MAX_FILL_FUNCTIONS)

    chunks: list[str] = ["\n/* -- generated support routines (bulk) "
                         "------------------------- */\n"]
    protos: list[str] = []
    bodies: list[str] = []
    calls: list[str] = []
    counter = 0
    sibs: list[tuple[str, int]] = []

    per_module = 64
    for m in range(0, n, per_module):
        module_fns = []
        for _ in range(min(per_module, n - m)):
            name = f"{rng.choice(_JPFX)}{rng.choice(_JNOUN)}_{counter:04d}"
            counter += 1
            sig_idx = rng.randrange(3)
            decl = _JSIGS[sig_idx][0].format(name=name)
            protos.append(decl + ";")
            body = _junk_body(rng, sig_idx, name, sibs[-8:] if sibs else [])
            bodies.append(decl + "\n{\n" + "\n".join(body) + "\n}")
            module_fns.append((name, sig_idx))
            sibs.append((name, sig_idx))
        # module dispatcher: calls every function in the module with real-ish
        # arguments, keeping the call graph dense
        mname = f"bulk_walk_{m // per_module:03d}"
        table = f"bulk_tbl_{m // per_module:03d}"
        tbl_entries = ", ".join(f"0x{rng.randrange(1, 0xff):02x}u" for _ in range(8))
        protos.append(f"static void {mname}(void);")
        dlines = [f"static const unsigned char {table}[8] = {{ {tbl_entries} }};",
                  f"static void {mname}(void)", "{",
                  "    unsigned acc = 0;"]
        for fname, sidx in module_fns:
            if sidx == 0:
                dlines.append(f"    acc ^= {fname}(acc ^ {table}[acc & 7]);")
            elif sidx == 1:
                dlines.append(f"    acc ^= {fname}({table}, sizeof {table});")
            else:
                dlines.append(f"    acc ^= (unsigned){fname}((int)acc, "
                              f"{table}[acc & 7]);")
        dlines += ["    g_aux_signature ^= acc;", "}"]
        bodies.append("\n".join(dlines))
        calls.append(f"    {mname}();")

    chunks.append("\n".join(protos))
    chunks.append("\n".join(bodies))
    # The sweep is a plain walker over every module. DllMain reaches it
    # through a runtime gate the compiler cannot fold (see the builders),
    # so the code stays compiled and reachable through a real call edge
    # (survives -O2 elimination) while never executing in practice.
    chunks.append("static void bulk_walk_all(void)\n{\n" + "\n".join(calls)
                  + "\n}")
    return "\n".join(chunks), "bulk_walk_all();", counter


def _thunk_asm(label: str, ptr: str, arch64: bool, junk: bool,
               rng: random.Random) -> str:
    """One top-level asm statement defining a wrapper function.

    The wrapper is a real framed function — prologue, optional benign filler,
    epilogue — that ends in a tail jump to the resolved address, exactly the
    tail-call pattern compilers emit. A tail jump (not a call) is mandatory
    for correctness: a call would shift the frame, so the callee would spill
    its register arguments into our saved RBP (shadow-space overlap) and read
    its stack-passed arguments from the wrong offsets. The tail jump hands
    the callee the pristine entry state: registers, stack and alignment
    exactly as the original caller provided them."""
    pfx = "" if arch64 else "_"  # i686 mingw symbols carry a leading _
    ins = [
        ".text",
        f".globl {pfx}{label}",
        f"{pfx}{label}:",
        "push " + ("%rbp" if arch64 else "%ebp"),
        "mov " + ("%rsp, %rbp" if arch64 else "%esp, %ebp"),
    ]
    if junk:
        fill = _x64_filler(rng) if arch64 else _x86_filler(rng)
        ins += [i.strip() for i in fill]
    ins.append("leave")  # restore RSP/RBP so the callee sees pristine state
    ins.append(f"jmp *{pfx}{ptr}(%rip)" if arch64 else f"jmp *{pfx}{ptr}")
    c_literal = "\\n".join(ins)  # newline escapes inside the C string
    return f'__asm__("{c_literal}");\n'


def _sanitize(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name)


def read_exports(path: str):
    """(exports, machine) of the PE at path. exports is a list of
    (name-or-None, ordinal) tuples."""
    pe = pefile.PE(path)
    try:
        exports = []
        dir_entry = pe.OPTIONAL_HEADER.DATA_DIRECTORY[
            pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]]
        if dir_entry.VirtualAddress:
            for sym in pe.DIRECTORY_ENTRY_EXPORT.symbols:
                exports.append((sym.name.decode() if sym.name else None,
                                sym.ordinal))
        return exports, pe.FILE_HEADER.Machine
    finally:
        pe.close()


def _def_lines_forward(exports, forward_module: str) -> list[str]:
    lines = ["EXPORTS"]
    for name, ordinal in exports:
        if name is not None:
            lines.append(f'    "{name}"={forward_module}."{name}" @{ordinal}')
        else:
            lines.append(f'    "export_ordinal_{ordinal}"='
                         f'{forward_module}.#{ordinal} @{ordinal} NONAME')
    return lines


def _def_lines_call(exports) -> list[str]:
    lines = ["EXPORTS"]
    for name, ordinal in exports:
        label = _sanitize(name) if name is not None else f"ord_{ordinal}"
        entry = name if name is not None else f"export_ordinal_{ordinal}"
        noname = " NONAME" if name is None else ""
        lines.append(f'    "{entry}"=t_{label} @{ordinal}{noname}')
    return lines


def _proxy_c_call(exports, dll_name: str, orig_name: str, seed: int,
                  junk: bool, rng: random.Random,
                  target_size: int = 0,
                  payload_obj: str | None = None) -> tuple[list[str], int]:
    """The call-style proxy.c body: pointer table, resolver, DllMain, and
    (added by the caller) asm thunks."""
    ptrs = []
    table = []
    for name, ordinal in exports:
        label = _sanitize(name) if name is not None else f"ord_{ordinal}"
        if name is not None:
            table.append(f'    {{"{name}", &fp_{label}}},')
        else:
            table.append(f'    {{NULL, (FARPROC *)&fp_{label},'
                         f' {ordinal}}},')  # ordinal resolve
        ptrs.append(f"static FARPROC fp_{label};")

    parts = [PROXY_C_HEAD.format(
        dll_name=dll_name, orig_name=orig_name,
        style_desc="wrapper functions calling into the renamed original",
        seed=seed)]

    bulk_count = 0
    if junk:
        decoy, init = _emit_decoy(rng)
        parts.append(decoy)
        parts.append(init)
        # Rough size already committed before the bulk fillers: resolver
        # table + strings + per-export thunk code + small decoy library.
        reserve = 96 * len(exports) + 8192 + 65536
        bulk, bulk_call, bulk_count = _emit_bulk(rng, target_size, reserve)
        if bulk:
            parts.append(bulk)
            parts.append(GATE_GLOBAL)

    parts += [
        "/* Resolved addresses of the original's exports. */",
        *ptrs,
        "",
        "typedef struct {",
        "    const char *name;   /* NULL -> resolve by ordinal */",
        "    FARPROC *ptr;",
        "    WORD ordinal;",
        "} aux_resolver_entry_t;",
        "",
        "static const aux_resolver_entry_t kResolve[] = {",
        *table,
        "};",
        "#define RESOLVE_COUNT (sizeof kResolve / sizeof kResolve[0])",
        "",
        f'static const wchar_t kOriginalDll[] = L"{orig_name}";',
        "static HMODULE h_original;",
        "",
        "static void resolve_original(void)",
        "{",
        "    h_original = LoadLibraryW(kOriginalDll);",
        "    if (!h_original)",
        "        return;",
        "    for (size_t i = 0; i < RESOLVE_COUNT; i++) {",
        "        if (kResolve[i].name)",
        "            *kResolve[i].ptr = GetProcAddress(h_original,"
        " kResolve[i].name);",
        "        else",
        "            *kResolve[i].ptr = GetProcAddress(h_original,"
        " MAKEINTRESOURCEA(kResolve[i].ordinal));",
        "    }",
        "}",
        "",
        _payload_section(payload_obj),
        "BOOL WINAPI DllMain(HINSTANCE hinstDLL, DWORD fdwReason,"
        " LPVOID lpReserved)",
        "{",
        "    (void)hinstDLL; (void)lpReserved;",
        "    if (fdwReason == DLL_PROCESS_ATTACH) {",
    ]
    if junk:
        parts += [
            "        FILETIME ft;",
            "        unsigned long long now;",
            "",
            "        /* Support-library init: only if the system clock reads",
            "         * the FILETIME epoch exactly (Jan 1, 1601) — never in",
            "         * practice, so none of this runs; it stays compiled and",
            "         * reachable through a real call edge. */",
            "        GetSystemTimeAsFileTime(&ft);",
            "        now = ((unsigned long long)ft.dwHighDateTime << 32)",
            "            | ft.dwLowDateTime;",
            "        g_epoch_gate = now;",
            "        if (now == 0) {",
            "            aux_init();",
        ]
        if bulk_count:
            parts.append("            " + bulk_call)
        parts.append("        }")
    parts += [
        "        resolve_original();",
        "        payload(); /* <<< call site — move/extend as you see fit */",
        "    }",
        "    return TRUE;",
        "}",
        "",
        "/* Wrapper functions: the export table points at real code; each",
        " * wrapper ends in a tail call to the resolved address — the only",
        " * ABI-safe way to forward a signature you do not know. */",
    ]
    return parts, bulk_count


def _proxy_c_forward(dll_name: str, orig_name: str, seed: int,
                     junk: bool, rng: random.Random,
                     target_size: int = 0,
                     payload_obj: str | None = None) -> tuple[str, int]:
    """The forward-style proxy.c: DllMain (+ optional decoy library)."""
    bulk_count = 0
    parts = [PROXY_C_HEAD.format(
        dll_name=dll_name, orig_name=orig_name,
        style_desc="export forwarders into the renamed original",
        seed=seed)]
    if junk:
        decoy, init = _emit_decoy(rng)
        parts.append(decoy)
        parts.append(init)
        reserve = 8192 + 65536  # no thunks in forward style
        bulk, bulk_call, bulk_count = _emit_bulk(rng, target_size, reserve)
        if bulk:
            parts.append(bulk)
            parts.append(GATE_GLOBAL)
    parts += [
        _payload_section(payload_obj),
        "BOOL WINAPI DllMain(HINSTANCE hinstDLL, DWORD fdwReason,"
        " LPVOID lpReserved)",
        "{",
        "    (void)hinstDLL; (void)lpReserved;",
        "    if (fdwReason == DLL_PROCESS_ATTACH) {",
    ]
    if junk:
        parts += [
            "        FILETIME ft;",
            "        unsigned long long now;",
            "",
            "        /* Support-library init: only if the system clock reads",
            "         * the FILETIME epoch exactly (Jan 1, 1601) — never in",
            "         * practice, so none of this runs; it stays compiled and",
            "         * reachable through a real call edge. */",
            "        GetSystemTimeAsFileTime(&ft);",
            "        now = ((unsigned long long)ft.dwHighDateTime << 32)",
            "            | ft.dwLowDateTime;",
            "        g_epoch_gate = now;",
            "        if (now == 0) {",
            "            aux_init();",
        ]
        if bulk_count:
            parts.append("            " + bulk_call)
        parts.append("        }")
    parts += [
        "        payload(); /* <<< call site — move/extend as you see fit */",
        "    }",
        "    return TRUE;",
        "}",
        "",
    ]
    return "\n".join(parts), bulk_count


