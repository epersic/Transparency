_DECOY_INIT_CALLS = {
    "crc32": "    aux_crc32_init();",
    "adler32": None,
    "b64": None,
    "hex": None,
    "hash": None,
    "utf8": None,
    "lcg": None,
}


def _emit_decoy(rng: random.Random) -> tuple[str, str]:
    """(file-scope code, init function) for a randomized decoy subset."""
    modules = [m for m in _DECOY_MODULES if rng.random() < 0.8] or ["hash"]
    rng.shuffle(modules)

    strings = rng.sample(_DECOY_STRINGS, rng.randint(6, len(_DECOY_STRINGS)))
    basis = rng.choice([2166136261, 5381, 16777619])

    parts = [
        "/* -- benign support code ------------------------------------------------ */",
        "",
        f"static const char *const kAuxStrings[] = {{",
        "".join(f'    "{s}",\n' for s in strings) + "};",
        "#define AUX_STRING_COUNT (sizeof kAuxStrings / sizeof kAuxStrings[0])",
        "",
        "static volatile uint32_t g_aux_signature;",
        "",
    ]
    for m in modules:
        parts.append(_DECOY_MODULES[m].replace("{lcg_seed}", str(rng.randrange(1 << 31))))

    body = [
        "static void aux_init(void)",
        "{",
    ]
    for m in modules:
        call = _DECOY_INIT_CALLS[m]
        if call:
            body.append(call)
    if "crc32" in modules:
        body.append("    g_aux_signature = aux_crc32(kAuxStrings[0],"
                    " strlen(kAuxStrings[0]));")
    if "hash" in modules:
        body.append(f"    g_aux_signature ^= aux_hash_string(kAuxStrings[0],"
                    f" {basis}u);")
    if "adler32" in modules:
        body.append("    g_aux_signature ^= aux_adler32(kAuxStrings,"
                    " sizeof(kAuxStrings));")
    if "lcg" in modules:
        body.append("    g_aux_signature ^= aux_lcg_next();")
    if "utf8" in modules:
        body.append("    g_aux_signature ^= (uint32_t)aux_utf8_length("
                    "kAuxStrings[0]);")
    if "b64" in modules:
        body.append("    char scratch[64];")
        body.append("    (void)aux_b64_encode((const uint8_t *)kAuxStrings[1],"
                    " strlen(kAuxStrings[1]), scratch, sizeof scratch);")
    if "hex" in modules:
        body.append("    char hexed[33];")
        body.append("    aux_hex_encode((const uint8_t *)&g_aux_signature,"
                    " sizeof g_aux_signature, hexed);")
    body += ["    (void)hexed;" if "hex" in modules and "b64" not in modules else None,
             "}",
             ""]
    body = [b for b in body if b is not None]
    return "\n".join(parts), "\n".join(body)


